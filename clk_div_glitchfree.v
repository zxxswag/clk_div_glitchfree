`timescale 1ns/1ps
//=============================================================================
// clk_div_glitchfree.v
//-----------------------------------------------------------------------------
// 功能 :
//   根据 3bit 分频系数 div_sel 产生 1~8 分频的输出时钟 clk_div。
//   输出时钟无毛刺, 且分频系数切换时无缝完成:
//   当前分频周期完整走完后, 新周期立即按新系数工作, 不产生窄脉冲。
//
// 端口 :
//   clk     : 输入时钟
//   rst_n   : 异步复位, 低有效 (内部已做复位释放同步)
//   div_sel : 分频系数 N-1, 编码如下 (按准静态配置信号处理, 内部 2 拍同步)
//               3'b000 -> ÷1      3'b100 -> ÷5
//               3'b001 -> ÷2      3'b101 -> ÷6
//               3'b010 -> ÷3      3'b110 -> ÷7
//               3'b011 -> ÷4      3'b111 -> ÷8
//   clk_div : 分频输出时钟 (不保证 50% 占空比)
//
// 无毛刺 + 无缝切换原理 :
//   1) 无缝切换 : div_sel 经 2 拍同步后, 只在计数器回绕 (分频周期边界)
//      时刻锁存进 ratio —— 切换永远发生在周期边界, 绝不会切在半周期中间。
//      切换请求最迟在 "2 拍同步 + 当前周期剩余长度" 后生效。
//   2) 无毛刺   : 输出采用 "时钟使能 en + 低电平锁存时钟门控 (ICG)" 结构。
//      en 只会在 clk 低电平期间进入锁存器, clk 高电平期间门控信号保持不变,
//      因此 clk_div = clk & en_l 上不可能出现任何毛刺 / 窄脉冲;
//      en 本身是寄存器输出, 计数器译码毛刺也不会传出。
//   3) 输出波形 : 每个分频周期 (N 个 clk) 内输出前 H = ceil(N/2) 个 clk 周期
//      的时钟窗, 输出周期 = N × Tclk。
//      N=1 时 en 恒为 1, clk_div = clk 直通; N=2 时 1 开 1 关, 占空比近 50%。
//
// 综合映射 :
//   FPGA : always@(*) 低电平锁存 + AND 是 BUFGCE (时钟使能) 的标准推断模板;
//   ASIC : 可直接把 "锁存+与门" 替换为库 ICG 单元 (如 CKLNQ)。
//=============================================================================

module clk_div_glitchfree (
    input  wire       clk,
    input  wire       rst_n,
    input  wire [2:0] div_sel,
    output wire       clk_div
);

    //-------------------------------------------------------------------------
    // 0) 复位释放同步 : 异步复位立即拉低, 释放时刻与 clk 同步,
    //    避免 recovery/removal 时序违例
    //-------------------------------------------------------------------------
    reg  rst_sync1, rst_sync2;
    wire rstn;

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) {rst_sync2, rst_sync1} <= 2'b00;
        else        {rst_sync2, rst_sync1} <= {rst_sync1, 1'b1};
    end
    assign rstn = rst_sync2;

    //-------------------------------------------------------------------------
    // 1) div_sel 两级同步 (div_sel 允许与 clk 异步, 按准静态配置处理)
    //-------------------------------------------------------------------------
    reg [2:0] sel_meta, sel_sync;
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) {sel_sync, sel_meta} <= 6'd0;       // 复位后默认 ÷1
        else        {sel_sync, sel_meta} <= {sel_meta, div_sel};
    end

    //-------------------------------------------------------------------------
    // 2) 分频计数器 + 周期边界锁存新系数 (无缝切换的核心)
    //    cnt 在 0 ~ ratio 间循环, 每次回绕时把同步后的新系数装入 ratio,
    //    保证任何切换都发生在完整分频周期之后
    //-------------------------------------------------------------------------
    reg  [2:0] cnt;
    reg  [2:0] ratio;                    // 当前生效的分频系数 N-1
    wire       wrap = (cnt == ratio);    // 分频周期最后一级

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            cnt   <= 3'd0;
            ratio <= 3'd0;
        end
        else if (wrap) begin
            cnt   <= 3'd0;
            ratio <= sel_sync;           // 只在周期边界加载新系数
        end
        else begin
            cnt <= cnt + 3'd1;
        end
    end

    //-------------------------------------------------------------------------
    // 3) 时钟使能 en : 每个分频周期 (N 个 clk) 的前 H 个周期开窗
    //    H = ceil(N/2) = (ratio>>1)+1 ; 输出不要求 50% 占空比
    //-------------------------------------------------------------------------
    wire [2:0] half    = (ratio >> 1) + 3'd1;
    wire [2:0] cnt_nxt = wrap ? 3'd0 : cnt + 3'd1;
    reg        en;

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) en <= 1'b0;                  // 复位期间关门
        else        en <= (cnt_nxt < half);      // 寄存器输出, 译码毛刺不出门
    end

    //-------------------------------------------------------------------------
    // 4) 低电平锁存时钟门控 (ICG / BUFGCE)
    //    en 只在 clk 低电平 (门关断) 期间进入锁存器, clk 高电平期间不变,
    //    故 clk_div 上任何时刻都不会出现窄脉冲
    //-------------------------------------------------------------------------
    reg en_l;
    always @(*) begin
        if (!clk) en_l = en;      // clk 低 : 透明 ; clk 高 : 锁存
    end
    // ASIC 替换 : ICG u_icg (.CP(clk), .E(en), .Q(en_l));

    assign clk_div = clk & en_l;

endmodule

